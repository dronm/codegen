package codegen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
)

const backendEnumManifestPath = ".codegen/backend-enums.json"
const backendEnumGeneratedHeader = "// Code generated by cmd/codegen. DO NOT EDIT.\n// Backend enum artifact: managed by Codegen.\n"

type backendEnumArtifact struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

type backendEnumManifest struct {
	Version int                   `json:"version"`
	Files   []backendEnumArtifact `json:"files"`
}

func safeBackendEnumArtifactPath(name string) bool {
	if name != path.Clean(name) || strings.Contains(name, "\\") || path.Dir(name) != "internal/models" {
		return false
	}
	return strings.HasSuffix(name, ".enum.gen.go") || name == "internal/models/enums_registry.gen.go"
}

// Resolve only fixed descendants of the configured root; do not follow a
// symlinked internal/models or .codegen directory while modifying owned files.
func backendEnumPath(root, relative string) (string, error) {
	parts := strings.Split(relative, "/")
	current := root
	for i, part := range parts {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		if info.Mode()&os.ModeSymlink != 0 || (i < len(parts)-1 && !info.IsDir()) {
			return "", fmt.Errorf("refusing backend enum output through non-directory or symlink %s", current)
		}
	}
	return current, nil
}

func readBackendEnumManifest(root string) (backendEnumManifest, []byte, error) {
	manifest := backendEnumManifest{Version: 1, Files: []backendEnumArtifact{}}
	filename, err := backendEnumPath(root, backendEnumManifestPath)
	if err != nil {
		return manifest, nil, err
	}
	data, err := os.ReadFile(filename)
	if errors.Is(err, fs.ErrNotExist) {
		return manifest, nil, nil
	}
	if err != nil {
		return manifest, nil, err
	}
	if err := json.Unmarshal(data, &manifest); err != nil || manifest.Version != 1 {
		return manifest, nil, fmt.Errorf("invalid backend enum ownership manifest %s (expected version 1)", filename)
	}
	seen := map[string]bool{}
	for _, file := range manifest.Files {
		_, digestErr := hex.DecodeString(file.SHA256)
		if !safeBackendEnumArtifactPath(file.Path) || seen[file.Path] || len(file.SHA256) != 64 || digestErr != nil {
			return manifest, nil, fmt.Errorf("invalid backend enum ownership entry %q in %s", file.Path, filename)
		}
		seen[file.Path] = true
	}
	return manifest, data, nil
}

func backendEnumHash(data []byte) string {
	hash := sha256.Sum256(data)
	return hex.EncodeToString(hash[:])
}

func verifyManagedBackendEnumFile(filename string) ([]byte, error) {
	info, err := os.Lstat(filename)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("refusing to overwrite/delete non-regular backend enum artifact %s", filename)
	}
	data, err := os.ReadFile(filename)
	if err != nil {
		return nil, err
	}
	if !bytes.HasPrefix(data, []byte(backendEnumGeneratedHeader)) {
		return nil, fmt.Errorf("refusing to overwrite/delete developer-owned backend enum file %s (generated enum marker is missing)", filename)
	}
	return data, nil
}

func (r Renderer) RenderBackendEnums(objects []ObjectView) error {
	enums, err := collectBackendEnums(objects)
	if err != nil {
		return err
	}
	// Also protect direct Renderer callers, not only the Generate entry point.
	if err := validateBackendEnumObjects(r.Config, objects); err != nil {
		return err
	}
	previous, manifestData, err := readBackendEnumManifest(r.Config.ServerRoot)
	if err != nil {
		return err
	}
	type output struct {
		filename string
		relative string
		content  []byte
	}
	outputs := []output{}
	add := func(relative, templateName string, value any) error {
		filename, err := backendEnumPath(r.Config.ServerRoot, relative)
		if err != nil {
			return err
		}
		if _, err := verifyManagedBackendEnumFile(filename); err != nil {
			return err
		}
		data, err := r.executeTemplate(filepath.Join(r.Config.TemplateDir, "go", templateName), value)
		if err != nil {
			return err
		}
		data, err = format.Source(data)
		if err != nil {
			return fmt.Errorf("format backend enum template %s: %w", templateName, err)
		}
		if !bytes.HasPrefix(data, []byte(backendEnumGeneratedHeader)) {
			return fmt.Errorf("backend enum template %s must retain the generated enum ownership header", templateName)
		}
		outputs = append(outputs, output{filename, relative, data})
		return nil
	}
	registrations := []BackendEnumView{}
	for _, enum := range enums {
		if enum.Managed {
			if err := add(path.Join("internal/models", enum.FileBase+".enum.gen.go"), "enum.go.tmpl", enum); err != nil {
				return err
			}
		}
		if enum.Register {
			registrations = append(registrations, enum)
		}
	}
	if len(registrations) > 0 {
		if err := add("internal/models/enums_registry.gen.go", "enum_registry.go.tmpl", BackendEnumsView{Enums: registrations}); err != nil {
			return err
		}
	}
	if len(outputs) == 0 && manifestData == nil {
		return nil // no new files in projects without managed backend enums
	}
	current := backendEnumManifest{Version: 1, Files: []backendEnumArtifact{}}
	expected := map[string]bool{}
	for _, item := range outputs {
		expected[item.relative] = true
		current.Files = append(current.Files, backendEnumArtifact{Path: item.relative, SHA256: backendEnumHash(item.content)})
	}
	stale := []string{}
	for _, file := range previous.Files {
		if expected[file.Path] {
			continue
		}
		filename, err := backendEnumPath(r.Config.ServerRoot, file.Path)
		if err != nil {
			return err
		}
		data, err := verifyManagedBackendEnumFile(filename)
		if err != nil {
			return err
		}
		if data != nil && backendEnumHash(data) != file.SHA256 {
			return fmt.Errorf("refusing to delete modified stale backend enum file %s; archive or remove it explicitly", filename)
		}
		stale = append(stale, filename)
	}
	if r.Config.Check && len(stale) > 0 {
		return fmt.Errorf("check failed: stale backend enum artifacts; run codegen generate: %s", strings.Join(stale, ", "))
	}
	content, err := json.MarshalIndent(current, "", "\t")
	if err != nil {
		return err
	}
	content = append(content, '\n')
	manifestPath, err := backendEnumPath(r.Config.ServerRoot, backendEnumManifestPath)
	if err != nil {
		return err
	}
	if r.Config.Check {
		for _, item := range outputs {
			actual, err := os.ReadFile(item.filename)
			if err != nil || !bytes.Equal(actual, item.content) {
				return fmt.Errorf("check failed: backend enum file %s is missing or outdated", item.filename)
			}
		}
		if !bytes.Equal(manifestData, content) {
			return fmt.Errorf("check failed: backend enum ownership manifest %s is missing or outdated", manifestPath)
		}
		return nil
	}
	for _, item := range outputs {
		if err := os.MkdirAll(filepath.Dir(item.filename), 0o755); err != nil {
			return err
		}
		if err := writeFileAtomic(item.filename, item.content, 0o644); err != nil {
			return err
		}
		fmt.Printf("generated %s\n", item.filename)
	}
	for _, filename := range stale {
		if err := os.Remove(filename); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		fmt.Printf("removed stale generated backend enum %s\n", filename)
	}
	if err := os.MkdirAll(filepath.Dir(manifestPath), 0o755); err != nil {
		return err
	}
	return writeFileAtomic(manifestPath, content, 0o644)
}
